// Builds the pull request comment. Model output is untrusted (the reviewed code can contain
// prompt injection), so every model-written string is sanitised before it goes into Markdown.

import type { Issue, RejectedIssue, Rule } from './types.ts';

export const COMMENT_MARKER = '<!-- llm-review -->';

export interface PullRequestFileReview {
  path: string;
  accepted: Issue[];
  rejected: RejectedIssue[];
  /** Valid findings on lines this pull request did not change. */
  outsideDiff: number;
  warnings: string[];
}

export interface CommentContext {
  repo: string;
  sha: string;
  model: string;
  rules: readonly Rule[];
  seconds: number;
  files: readonly PullRequestFileReview[];
}

/** Finds the commit a previous comment was written for. */
export function reviewedSha(body: string): string | null {
  return /<!-- llm-review-sha: ([0-9a-f]{7,40}) -->/.exec(body)?.[1] ?? null;
}

export function buildComment(ctx: CommentContext): string {
  const findings = ctx.files.flatMap((f) => f.accepted.map((issue) => ({ path: f.path, issue })));
  const rejected = ctx.files.flatMap((f) => f.rejected.map((r) => ({ path: f.path, ...r })));
  const outsideDiff = ctx.files.reduce((sum, f) => sum + f.outsideDiff, 0);
  const warnings = ctx.files.flatMap((f) => f.warnings.map((w) => `${f.path}: ${w}`));
  const ruleTitles = new Map(ctx.rules.map((r) => [r.id, r.title]));

  const lines: string[] = [
    COMMENT_MARKER,
    `<!-- llm-review-sha: ${ctx.sha} -->`,
    '## 🤖 LLM review',
    '',
    `Model \`${ctx.model}\` · rules ${ctx.rules.map((r) => r.id).join(', ')} · commit \`${ctx.sha.slice(0, 7)}\` · ${ctx.files.length} file(s) · ${ctx.seconds.toFixed(0)}s`,
    '',
  ];

  if (findings.length === 0) {
    lines.push('✅ No rule violations found in the changed lines.');
  } else {
    lines.push(
      `Found **${findings.length}** issue(s) in the changed lines:`,
      '',
      '| File | Line | Rule | Finding | Suggestion |',
      '| --- | --- | --- | --- | --- |',
    );
    for (const { path, issue } of findings) {
      const link = `https://github.com/${ctx.repo}/blob/${ctx.sha}/${path}#L${issue.line}`;
      const rule = `${issue.rule}: ${ruleTitles.get(issue.rule) ?? ''}`;
      lines.push(
        `| \`${path}\` | [${issue.line}](${link}) | ${cell(rule)} | ${cell(issue.message)} | ${cell(issue.suggestion ?? '')} |`,
      );
    }
  }

  if (rejected.length > 0) {
    lines.push(
      '',
      `<details><summary>Rejected by the evidence check (${rejected.length})</summary>`,
      '',
      '| File | Line | Rule | Reason |',
      '| --- | --- | --- | --- |',
      ...rejected.map((r) => `| \`${r.path}\` | ${r.issue.line} | ${cell(r.issue.rule)} | ${cell(r.reason)} |`),
      '',
      '</details>',
    );
  }
  if (outsideDiff > 0) {
    lines.push('', `_${outsideDiff} finding(s) on lines this pull request did not change were left out._`);
  }
  if (warnings.length > 0) {
    lines.push('', ...warnings.map((w) => `> ⚠️ ${cell(w)}`));
  }
  lines.push(
    '',
    '<sub>Generated by a local model via Ollama. Findings can be wrong; this comment is updated on every run.</sub>',
  );
  return lines.join('\n');
}

/** Makes model text safe for a Markdown table cell: one line, no HTML, no pipes, no @mentions. */
function cell(text: string): string {
  return text
    .replace(/\s+/g, ' ')
    .replace(/[<>]/g, (c) => (c === '<' ? '&lt;' : '&gt;'))
    .replace(/\|/g, '\\|')
    .replace(/@(?=\w)/g, '@​')
    .trim()
    .slice(0, 300);
}
